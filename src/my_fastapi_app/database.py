# src/my_fastapi_app/database.py
"""
Инициализация подключения к базе данных.

Здесь создаётся:
  1. Асинхронный движок (engine) — управляет пулом соединений.
  2. Фабрика сессий (async_session_maker) — создаёт сессии для запросов.
  3. Базовый класс моделей (Base) — от него наследуются все ORM-модели.
  4. Зависимость get_db — предоставляет сессию эндпоинтам.
"""

from collections.abc import AsyncGenerator

from sqlalchemy.ext.asyncio import (
    AsyncSession,
    async_sessionmaker,
    create_async_engine,
)
from sqlalchemy.orm import DeclarativeBase

from my_fastapi_app.config import get_settings

# Читаем настройки один раз при импорте модуля.
settings = get_settings()


# ─────────────────────────────────────────────────────────────────────────────
# 1. ДВИЖОК (ENGINE)
# ─────────────────────────────────────────────────────────────────────────────
# create_async_engine создаёт движок для работы с БД в асинхронном режиме.
#
# Параметры (важные для продакшена):
#   - echo=True  → логирование всех SQL-запросов. ТОЛЬКО для разработки!
#   - pool_size  → размер пула соединений. По умолчанию 5.
#   - max_overflow → сколько можно создать сверх pool_size при пиковой нагрузке.
#   - pool_pre_ping=True → перед выдачей соединения из пула проверять, живо ли оно.
#     Это спасает от "connection closed" после долгого простоя.
#
# echo берём из settings.debug — в dev логируем, в prod нет.
engine = create_async_engine(
    settings.database_url,
    echo=settings.debug,
    pool_pre_ping=True,  # Спасает от «полуживых» соединений после простоя БД. В продакшене — обязательно
)

# ─────────────────────────────────────────────────────────────────────────────
# 2. ФАБРИКА СЕССИЙ
# ─────────────────────────────────────────────────────────────────────────────
# async_sessionmaker — фабрика, которая создаёт новые сессии.
#
# Параметры:
#   - bind=engine → привязка к нашему движку.
#   - expire_on_commit=False → после commit() объекты остаются "живыми"
#     и к ним можно обращаться без нового запроса к БД. По умолчанию True —
#     это приводит к неожиданным ошибкам при сериализации ответа после commit.
async_session_maker = async_sessionmaker(
    bind=engine,
    expire_on_commit=False,
)

# ─────────────────────────────────────────────────────────────────────────────
# 3. БАЗОВЫЙ КЛАСС МОДЕЛЕЙ
# ─────────────────────────────────────────────────────────────────────────────
# DeclarativeBase — базовый класс SQLAlchemy 2.0 для декларативных моделей.
# Все наши модели (Item, User, Order...) будут наследоваться от него.
#
# Раньше был declarative_base(), но в SQLAlchemy 2.0 его заменили на класс
# DeclarativeBase — это даёт лучшую типизацию для mypy.


class Base(DeclarativeBase):
    """Базовый класс для всех ORM-моделей приложения."""


# ─────────────────────────────────────────────────────────────────────────────
# 4. ЗАВИСИМОСТЬ GET_DB
# ─────────────────────────────────────────────────────────────────────────────
async def get_db() -> AsyncGenerator[AsyncSession, None]:
    """
    Зависимость FastAPI: предоставляет сессию БД для одного запроса.

    Использование:
        @router.get("/items")
        async def read_items(db: Annotated[AsyncSession, Depends(get_db)]):
            ...

    Как работает:
      - async with откроет сессию перед эндпоинтом.
      - yield вернёт её в эндпоинт.
      - После завершения запроса (успех или исключение)
        контекстный менеджер закроет сессию и вернёт соединение в пул.

    Почему именно так:
      - Гарантирует закрытие соединения даже при исключении.
      - Одно соединение — один запрос. Избегаем утечек.
      - В коммерческой разработке утечка соединений — частая причина падения
        продакшена (заканчивается пул → новые запросы виснут).
    """
    async with (
        async_session_maker() as session
    ):  # 	Гарантирует закрытие сессии через __aexit__ даже при исключении
        yield session
